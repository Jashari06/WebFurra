const NAMES = { facebook: 'Facebook', instagram: 'Instagram', tiktok: 'TikTok' };

/** Facebook-, Instagram- und TikTok-Symbole. Ohne Adresse in CONFIG.social nur in der lokalen Vorschau sichtbar. */
export default function Social({ className = '' }) {
  const links = Object.keys(ICONS)
    .map((key) => [key, CONFIG.social?.[key] || ''])
    .filter(([, url]) => url || import.meta.env.DEV);
  if (!links.length) return null;
  return (
    <ul className={`social ${className}`.trim()}>
      {links.map(([key, url]) => (
        <li key={key}>
          <a
            href={url || '#'}
            target={url ? '_blank' : undefined}
            rel={url ? 'noopener noreferrer' : undefined}
            aria-label={NAMES[key]}
            title={NAMES[key]}
            onClick={url ? undefined : (e) => e.preventDefault()}
          >
            <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">{ICONS[key]}</svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
